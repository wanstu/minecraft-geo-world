#!/usr/bin/env python3
"""Read-only preflight for genuine Minecraft GeoWorld voxel acceptance saves.

Requires only the Python standard library. It checks level.dat (NBT) AND the
persisted GeoWorld binding before a save may be used as voxel evidence.
"""
from __future__ import annotations

import argparse
import gzip
import json
import struct
import sys
from pathlib import Path


class NBTReader:
    def __init__(self, data: bytes):
        self.data = memoryview(data)
        self.pos = 0

    def take(self, length: int) -> bytes:
        if length < 0 or self.pos + length > len(self.data):
            raise ValueError("truncated or invalid NBT length")
        value = bytes(self.data[self.pos : self.pos + length])
        self.pos += length
        return value

    def numeric(self, format_code: str):
        size = struct.calcsize(">" + format_code)
        return struct.unpack(">" + format_code, self.take(size))[0]

    def string(self) -> str:
        size = self.numeric("H")
        return self.take(size).decode("utf-8")

    def tag(self, kind: int):
        if kind == 1:
            return self.numeric("b")
        if kind == 2:
            return self.numeric("h")
        if kind == 3:
            return self.numeric("i")
        if kind == 4:
            return self.numeric("q")
        if kind == 5:
            return self.numeric("f")
        if kind == 6:
            return self.numeric("d")
        if kind == 7:
            return self.take(self.numeric("i"))
        if kind == 8:
            return self.string()
        if kind == 9:
            item = self.numeric("B")
            size = self.numeric("i")
            if size < 0 or size > 10_000_000:
                raise ValueError("invalid NBT list length")
            return [self.tag(item) for _ in range(size)]
        if kind == 10:
            fields = {}
            while True:
                field_kind = self.numeric("B")
                if field_kind == 0:
                    return fields
                field_name = self.string()
                fields[field_name] = self.tag(field_kind)
        if kind == 11:
            size = self.numeric("i")
            return self.take(size * 4)
        if kind == 12:
            size = self.numeric("i")
            return self.take(size * 8)
        raise ValueError(f"invalid NBT tag type: {kind}")


def parse_level_dat(path: Path) -> dict:
    reader = NBTReader(gzip.decompress(path.read_bytes()))
    if reader.numeric("B") != 10:
        raise ValueError("level.dat root is not a compound")
    reader.string()  # root name
    return reader.tag(10)


def parse_binding(path: Path) -> dict[str, str]:
    # This file is generated by GeoWorldBinding.write. No multiline
    # properties or special escaping is used in these required fields.
    fields: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith(("#", "!")):
            continue
        if "=" not in line:
            raise ValueError(f"malformed GeoWorld binding property: {line!r}")
        key, value = line.split("=", 1)
        fields[key.strip()] = value.strip()
    return fields


def inspect(world: Path, expected_rules: str, expected_seed: int | None) -> dict:
    failures: list[str] = []
    report = {"world": str(world), "checks": {}, "failures": failures}
    level_path = world / "level.dat"
    if not level_path.is_file():
        return {**report, "pass": False, "failures": ["level.dat missing"]}

    try:
        data = parse_level_dat(level_path)["Data"]
        worldgen = data["WorldGenSettings"]
        generator = worldgen["dimensions"]["minecraft:overworld"]["generator"]["type"]
        seed = int(worldgen["seed"])
    except (OSError, ValueError, KeyError, TypeError, EOFError) as exc:
        return {**report, "pass": False, "failures": [f"cannot inspect level.dat world generation: {exc}"]}

    report["checks"]["generator"] = generator
    report["checks"]["worldSeed"] = seed
    if generator != "geoworld:geoworld":
        failures.append(f"wrong generator {generator!r}; select GeoWorld world preset when creating a NEW world")
    if expected_seed is not None and seed != expected_seed:
        failures.append(f"seed mismatch: actual {seed}; expected {expected_seed}")

    geo = world / "data" / "geoworld"
    binding_path = geo / "geoworld.properties"
    if not binding_path.is_file():
        failures.append("GeoWorld binding missing (data/geoworld/geoworld.properties)")
    else:
        try:
            properties = parse_binding(binding_path)
            report["checks"]["bindingRules"] = properties.get("generationRulesVersion")
            report["checks"]["bindingSeed"] = properties.get("seed")
            report["checks"]["bindingVersion"] = properties.get("version")
            if properties.get("format") != "geoworld-binding":
                failures.append("invalid GeoWorld binding format")
            if properties.get("generationRulesVersion") != expected_rules:
                failures.append(f"rules mismatch: binding {properties.get('generationRulesVersion')!r}, expected {expected_rules!r}")
            if properties.get("seed") != str(seed):
                failures.append("binding seed disagrees with level.dat seed")
            model_name = properties.get("model", "world.geoworld")
            if Path(model_name).name != model_name or not (geo / model_name).is_file():
                failures.append("bound model file missing or path invalid")
        except (OSError, ValueError) as exc:
            failures.append(f"invalid GeoWorld binding: {exc}")

    region_dir = world / "region"
    report["checks"]["regionFiles"] = len(list(region_dir.glob("*.mca"))) if region_dir.is_dir() else 0
    if report["checks"]["regionFiles"] == 0:
        failures.append("no saved Minecraft Anvil regions; actual block inspection is impossible")
    report["pass"] = not failures
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("world", type=Path)
    parser.add_argument("--expect-rules", default="geoworld-rules-v1.1.23")
    parser.add_argument("--expect-seed", type=int)
    parser.add_argument("--output", type=Path, help="optional JSON report file")
    args = parser.parse_args()
    result = inspect(args.world, args.expect_rules, args.expect_seed)
    payload = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    print(payload, end="")
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(payload, encoding="utf-8")
    return 0 if result["pass"] else 2


if __name__ == "__main__":
    sys.exit(main())
