package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"geoworld/acceptance"
)

func main() {
	fullPath := flag.String("full", "", "full acceptance JSON generated by geoworld-full-acceptance")
	outputDir := flag.String("output-dir", "build/manual-acceptance", "output directory")
	base := flag.String("base", "geoworld-spot-acceptance", "output filename base")
	perBig := flag.Int("per-big", 2, "items selected from each big category")
	flag.Parse()
	if *fullPath == "" {
		fatal(fmt.Errorf("-full is required"))
	}
	raw, err := os.ReadFile(*fullPath)
	if err != nil {
		fatal(err)
	}
	var full acceptance.ManualTable
	if err := json.Unmarshal(raw, &full); err != nil {
		fatal(err)
	}
	table, err := acceptance.BuildSpotTable(full, *perBig)
	if err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(*outputDir, 0o755); err != nil {
		fatal(err)
	}
	jsonData, err := acceptance.SpotTableJSON(table)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*outputDir, *base+".json"), jsonData, 0o644); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*outputDir, *base+".md"), []byte(acceptance.SpotTableMarkdown(table)), 0o644); err != nil {
		fatal(err)
	}
	csvFile, err := os.Create(filepath.Join(*outputDir, *base+".csv"))
	if err != nil {
		fatal(err)
	}
	if err := acceptance.WriteSpotTableCSV(csvFile, table); err != nil {
		_ = csvFile.Close()
		fatal(err)
	}
	if err := csvFile.Close(); err != nil {
		fatal(err)
	}
	fmt.Printf("spot acceptance table: %s (%d big categories x %d)\n", *outputDir, len(table.BigCategories), table.PerBigCategory)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "geoworld-spot-acceptance:", err)
	os.Exit(1)
}
